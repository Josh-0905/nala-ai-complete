export function insertHundredRecipes(): void {
  console.log(`🚀 Checking and inserting 103 additional culinary recipes into NALA AI...`);

  const insertRecipe = db.prepare(`
    INSERT OR REPLACE INTO recipes (
      id, name, description, cuisine, meal_type, diet_type, difficulty,
      preparation_time, cooking_time, total_time, servings,
      instructions, nutrition_data, estimated_cost, image_url, tags
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
  `);

  const insertRecipeIngredient = db.prepare(`
    INSERT INTO recipe_ingredients (id, recipe_id, ingredient_id, ingredient_name, quantity, unit, category, is_optional)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
  `);

  const insertReview = db.prepare(`
    INSERT INTO recipe_reviews (id, recipe_id, user_id, user_name, user_avatar, rating, title, comment, tags, helpful_count, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
  `);

  const transaction = db.transaction((recipes: NewRecipeItem[]) => {
    for (const r of recipes) {
      insertRecipe.run(
        r.id,
        r.name,
        r.description,
        r.cuisine,
        r.meal_type,
        r.diet_type,
        r.difficulty,
        r.preparation_time,
        r.cooking_time,
        r.total_time,
        r.servings,
        JSON.stringify(r.instructions),
        JSON.stringify(r.nutrition),
        r.estimated_cost,
        r.image_url,
        JSON.stringify(r.tags)
      );

      // Delete existing ingredients for this recipe to prevent duplicates
      db.prepare('DELETE FROM recipe_ingredients WHERE recipe_id = ?').run(r.id);

      for (const ing of r.ingredients) {
        insertRecipeIngredient.run(
          uuidv4(),
          r.id,
          null,
          ing.name,
          ing.quantity,
          ing.unit,
          ing.category,
          0
        );
      }

      // Add a couple of realistic reviews if none exist
      const existingReviews = db.prepare('SELECT count(*) as count FROM recipe_reviews WHERE recipe_id = ?').get(r.id) as { count: number };
      if (existingReviews.count === 0) {
        insertReview.run(
          uuidv4(),
          r.id,
          null,
          'Chef Rohan',
          'https://images.unsplash.com/photo-1507003211169-0a1dd7228f2d?auto=format&fit=crop&w=150&q=80',
          5,
          'Restaurant quality at home!',
          `Prepared this with NALA AI step timers. The flavor balance was exceptional and loved by the whole family!`,
          JSON.stringify(['Family Favorite', 'Restaurant Quality']),
          18,
          new Date(Date.now() - 3 * 86400000).toISOString()
        );

        insertReview.run(
          uuidv4(),
          r.id,
          null,
          'Pooja K.',
          'https://images.unsplash.com/photo-1494790108377-be9c29b29330?auto=format&fit=crop&w=150&q=80',
          5,
          'Super straightforward instructions',
          `Turned out delicious on the first try. Missing ingredient feature saved me from forgetting essentials!`,
          JSON.stringify(['Quick & Easy', 'Verified Cook']),
          12,
          new Date(Date.now() - 6 * 86400000).toISOString()
        );
      }
    }
  });

  transaction(hundredRecipes);

  const totalCount = db.prepare('SELECT count(*) as count FROM recipes').get() as { count: number };
  const totalReviews = db.prepare('SELECT count(*) as count FROM recipe_reviews').get() as { count: number };
  console.log(`✅ Successfully expanded recipe catalog! Total recipes now: ${totalCount.count}. Total reviews: ${totalReviews.count}`);
}

if (process.argv[1]?.endsWith('add100Recipes.ts') || process.argv[1]?.endsWith('add100Recipes.js')) {
  insertHundredRecipes();
}
